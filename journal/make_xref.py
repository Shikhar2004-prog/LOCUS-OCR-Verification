"""Cross-document references between the main article and the supplementary material.

Reads the label numbers of each document from its .aux file and writes them as macros, so that
\\sref{label} in one document prints the number of that label in the other (e.g. ``S3``).
  locus_journal.aux       -> j_xref_main.tex  (read by the supplement)
  locus_supplementary.aux -> j_xref_supp.tex  (read by the main article)
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
pat = re.compile(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}")
for aux, out in (("locus_journal.aux", "j_xref_main.tex"), ("locus_supplementary.aux", "j_xref_supp.tex")):
    p = os.path.join(here, aux)
    if not os.path.exists(p):
        print("missing", aux); continue
    labs = {}
    for m in pat.finditer(open(p).read()):
        if not m.group(1).endswith("@cref") and m.group(2):
            labs[m.group(1)] = m.group(2)
    lines = ["% generated by make_xref.py from " + aux, "\\makeatletter"]
    lines += [f"\\@namedef{{xr@{k}}}{{{v}}}" for k, v in sorted(labs.items())]
    if aux == "locus_journal.aux":  # citations in the supplement use the main article's reference numbers
        lines += [l for l in open(p).read().splitlines() if l.startswith("\\bibcite{")]
    lines += ["\\makeatother"]
    open(os.path.join(here, out), "w").write("\n".join(lines) + "\n")
    print(out, len(labs), "labels")
